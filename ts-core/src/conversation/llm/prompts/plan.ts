    "- goTo.params.x / y / z 必须是数字",
    "- 禁止 demoMineIron 或任何一键 demo（演示） 函数",
    "",
    "# 正例",
    '砍 5 个木头 => {"code":"await reply(\\"好的，我去砍 5 个木头喵~\\"); const task = await runGoal(\\"砍 5 个木头\\", async () => { const result = await cutTree(5); if (result.ok === false) { throw new Error(result.error.code); } }); await report(task);"}',
