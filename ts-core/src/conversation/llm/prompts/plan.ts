    "禁止输出 type、skill、params、skill_call、sandbox_code、reply、reason。",
    "code 第一段必须 reply(...)；主体必须用 runGoal(...) 包住；最后必须 await report(task)。",
    "不要总结历史，不要说“根据历史记录”，不要解释为什么这样规划。",
    "",
    "# 输出契约 2/3",
    '最终答案必须只输出可被 JSON.parse 直接解析的 {"code":"..."}。',
